// 底栏 ➕ 创作按钮上的看板娘（见 src/components/CreatePerch.tsx）。
//
// 她是一只**常驻的 app 宠物**，不是"切 Tab 才蹦一下的挂件"：
//   idle 一直在轻轻呼吸/晃头，每隔几秒随机挑一个反应动作演一遍再回到 idle。
//
// 用法（仓库根目录，需要 .env.local 里的 ARK_API_KEY）：
//   IMGTOOLS=<装了 sharp/ffmpeg-static 的目录> node design/gen-createbtn-sprites.mjs . [idle,wave]
// 产物：public/createbtn/{key}.webp + 中间产物缓存 design/createbtn-src/（不入仓）
//
// ★★ 构图的**唯一要求**：双手必须平放在画面最下沿的正中央。
//   缩小后的圆形加号按钮就摆在那个位置、盖在她身前 —— 于是读出来就是
//   「她的手搭在按钮上 / 从背后抱着按钮」。这是 ../perch/ 那六张挂件的同一招
//   （那边是"双手实打实压在图标顶沿"），已经验证过在 40–50px 上成立。
//   手的位置画歪了，按钮和她就变成两个各自为政的东西，怎么调 CSS 都救不回来。
//
// ★ 加号本身**不画进贴图**：它是 components/Icon 的矢量 plus，缩到 18px 也清晰，
//   而且提示词里写死了"无任何文字、字母、数字、符号"。位图画的加号一定更糊。
//
// ★ 四个反应动作的 A 端点都用 `aFrom: "idle"` 复用 idle 的末帧：
//   反应是「从待机姿势出发 → 做个动作 → 原路收回待机」，正播完再倒播回来就回到了
//   第 0 帧，正好接上 idle 循环。各自重出 A 帧的话，每次演完都会跳一下。
//
// ★ 不要画单眼眨眼。实测这个模型最容易画崩的就是单眼闭合（闭眼弧线朝上反、
//   还叠一道多余睫毛线），gen-create-covers.mjs 里为此专门写了"双眼对称"的约束。
//   俏皮感用手势和头部角度表达。
