// 底栏中间 ➕ 创作按钮上的看板娘（见 src/components/CreatePerch.tsx）。
//
// 四套不同的邀请动作 + 不同的表情，每次切 Tab 随机换一套演一遍——
// 目的很直白：把用户的注意力从"我在浏览"拉到"我可以创作"。
// 一套固定动作看三次就成了背景板，随机轮换才会让人多看一眼。
//
// 用法（仓库根目录，需要 .env.local 里的 ARK_API_KEY）：
//   IMGTOOLS=<装了 sharp/ffmpeg-static 的目录> node design/gen-createbtn-sprites.mjs . [invite,cheer]
// 产物：public/createbtn/{key}.webp + 中间产物缓存 design/createbtn-src/（不入仓）
//
// ★ 她手里【不拿加号】。加号仍然是那枚矢量图标（components/Icon 的 plus），
//   角色从按钮后面探出来抱住它 —— 与 CharacterPerch 那六个挂件同一套语言。
//   让模型去画一个「+」是两头坏：stage 里写死了无任何文字与符号（写符号本来就不稳），
//   而且位图画的加号缩到 26px 一定比矢量糊。「Q 版看板娘 + 加号」是两个元素合成一个按钮，
//   不是把加号画进贴图里。
//
// ★ 走 Q 版：按钮直径 48px，角色宽度约 84px。正片那张脸缩到这里就是一团糊。
//   身份由流水线的 qRef（perch/save.webp 第 8 帧）锁住——和底栏那六个挂件是同一个人。
//
// ★ 12 帧 / 单格 200px：比 perch 那六张（8 帧 /160px）都高一档，因为这颗按钮是
//   整个底栏唯一的主 CTA，也是四套里唯一会被反复看到的动画。四张合计约 600KB。
//
// ★ 不要画单眼眨眼。实测这个模型最容易画崩的就是单眼闭合（闭眼弧线朝上反、
//   还叠一道多余睫毛线），gen-create-covers.mjs 里为此专门写了"双眼对称"的约束。
//   俏皮感用「比剪刀手」「叉腰」这类手势表达，不要靠眨眼。
