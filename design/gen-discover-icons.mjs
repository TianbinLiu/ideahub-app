// 分区页六个分区入口的图标（见 src/pages/DiscoverPage.tsx 的 CategoryIcon）。
//
// 每个分区一张 8 帧精灵图，**两端各当一个状态**（与素材按钮 cardbtn 同一套做法）：
//   未选中 = 第 0 帧（道具收着、神情安静）
//   选中   = 第 7 帧（道具亮出来、表情张扬）
// 正播 = 选中，倒播 = 取消选中，两端靠 animation-fill-mode: forwards 定格。
// 做成两张静态图的话，切换只能靠淡入淡出，那是"换了张贴纸"而不是"她动了一下"。
// 所以 **a 必须是未选中态、b 必须是选中态，顺序不能反**。
//
// 用法（仓库根目录，需要 .env.local 里的 ARK_API_KEY）：
//   IMGTOOLS=<装了 sharp/ffmpeg-static 的目录> node design/gen-discover-icons.mjs . [drama,scifi]
// 产物：public/discover/{key}.webp + 中间产物缓存 design/discover-src/（不入仓）
//
// ★ 走 Q 版而不是正片：图标直径只有 48–56px，正片那张脸缩到这个尺寸就是一团糊。
//   身份由流水线的 qRef（perch/save.webp 第 8 帧）锁住——她和底栏那六个挂件是同一个人。
//
// ★ 单格 180px = 渲染尺寸（最大 56px）的 3.2 倍，够 3x 屏；与 cardbtn 同一档。
//   六张合计约 600KB，是要打进 APK 的，别随手加大。
//
// ★ 提示词里绝对不要出现文字/数字/符号类的道具（问号、字母牌之类）：
//   stage 里明确要求「无任何文字、字母、数字」，两边打架时模型会两头不讨好，
//   而且文生图写符号本来就不稳。分区特色一律用**实物道具**表达。
