// 「角色趴坐在图标上」——激活态才出现的二次元 Q 版角色。
//
// 形象即创作入口 /create 三张封面里的同一位角色：
//   银白长发 · 薄荷绿挑染 · 金色五角星发饰 · 青蓝大眼 · 藏蓝短披风 + 金色圆扣 + 白立领
//
// ★ 为什么只在激活时出现（而不是常驻）：
//   右侧栏 4 个按钮 + 底栏 4 个 Tab = 8 个位置。全挂角色会把画面塞满，
//   而首页是全出血视频，任何常驻装饰都在跟内容抢注意力。
//   只在「你刚点了赞/收藏」「你正在这个 Tab」时现身，角色就成了对操作的回应，
//   而不是背景噪音。
//
// ★ 为什么是位图而不是内联 SVG（这里推翻过两版手写矢量）：
//   目标画风是渐变上色 + 发丝高光 + 线稿描边的日系手绘感（对标 B 站底栏那种角色 Tab）。
//   这种质感来自逐像素的明暗过渡，手写 path 只能拼平涂色块——
//   两版矢量分别败在「三层头发同色糊成一个钟形罩」和「扁平色块不像二次元」，
//   问题不在画得不够细，而在【矢量平涂做不出上色】。
//   所以改为用项目自带的 Seedream 生成一张 Q 版半身像，绿幕抠图后作为贴图。
//   代价是多一个 17KB 的资源；换来的是画风真正对上了。
//
// ★ 为什么是半身像（没有腿）：
//   参考的角色 Tab 都是胸像。腿在 ~50px 下只会缩成两根看不清的小棍，
//   而且「手往前伸捧住图标」比「腿垂在图标前」更贴合「抱住图标」这个诉求。
//
// 资源生成方式记录在 public/perch/README.md，需要换形象时照着重跑即可。
import { memo } from "react";

/** 贴图原始尺寸，用来算等比高度。改图时同步改这里。 */
const ART_W = 160;
const ART_H = 165;

/**
 * 趴坐在图标顶部的角色。
 *
 * 定位约定：调用方给父元素 `relative`，本组件绝对定位到图标【上边缘】，
 * 双手垂到图标正面（bottom 取图标尺寸的比例），形成「捧住图标」的关系。
 * bottom 用比例而非固定 px —— 23px 的 Tab 图标与 28px 的右栏图标若共用固定偏移，
 * 会一个悬空一个陷进去。
 *
 * ★ 0.78 这个值是量出来的，不是估的：
 *   原先取 0.52，实测角色压掉了图标【46%】的高度 —— 底栏「首页」那格看过去
 *   只剩一个角色，房子图标完全认不出来，旁边三个 Tab 却是清晰图标。
 *   图标是导航控件，盖掉它等于把功能换成了装饰。取 0.78 后重叠约 22%，
 *   只有双手搭在图标顶沿，图标下方 3/4 的识别特征完整保留。
 *   注意重叠比例只由 bottom 与图标高度决定，与角色自身大小无关。
 */
function CharacterPerchImpl({ size = 28, className = "" }: { size?: number; className?: string }) {
  // 1.75×：小于这个比例，脸上的眼睛/腮红会缩到看不清，就退回成一个彩色斑点，
  // 那正是前两版失败的地方。角色坐在图标【上方】而非覆盖其上，宽一点不伤图标辨识。
  const w = Math.round(size * 1.75);

  return (
    <span
      className={`perch-pop pointer-events-none absolute left-1/2 z-10 -translate-x-1/2 ${className}`}
      style={{ bottom: `${Math.round(size * 0.78)}px`, width: w }}
      aria-hidden
    >
      {/* 不做预加载：底栏总有一个 Tab 处于激活态，首屏就会渲染本组件并拉取贴图，
          等用户点到赞/收藏时早已在缓存里，额外加 <link rel=preload> 是多余的。 */}
      <img
        src="/perch/chibi.png"
        alt=""
        width={w}
        height={Math.round((w * ART_H) / ART_W)}
        draggable={false}
        decoding="async"
      />
    </span>
  );
}

/** memo：右侧栏与底栏在滚动/播放中频繁重渲染，角色无状态，不必跟着重画 */
export const CharacterPerch = memo(CharacterPerchImpl);
export default CharacterPerch;
