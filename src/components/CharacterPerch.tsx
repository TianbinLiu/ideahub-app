// 「角色趴坐在图标上」——激活态才出现的二次元 Q 版少女。
//
// 角色取自创作入口 /create 三张封面图（studio / workflow / simple）里的同一位少女：
//   银白长直发 · 右侧一大绺薄荷挑染 · 左侧金色五角星发饰
//   青蓝色大眼 + 白色高光 · 张嘴笑 · 腮红
//   藏蓝短披风 + 金色圆扣 + 白色立领衬衫
//
// ★ 为什么只在激活时出现（而不是常驻）：
//   右侧栏 4 个按钮 + 底栏 4 个 Tab = 8 个位置。全挂角色会把画面塞满，
//   而首页是全出血视频，任何常驻装饰都在跟内容抢注意力。
//   只在「你刚点了赞/收藏」「你正在这个 Tab」时现身，角色就成了对操作的回应，
//   而不是背景噪音 —— 同样的绘制成本，换来记忆点而非干扰。
//
// ★ 尺寸与细节的取舍（这里推翻过一版）：
//   初版按「图标才 26px，画什么都会糊」的思路，把眼睛/嘴/腮红全砍了，
//   只留剪影 + 发色块 + 星星。结果是丑且完全不二次元 ——
//   因为二次元的识别度几乎全部由【眼睛】承担：大眼白 + 青蓝虹膜 + 白高光 +
//   粗上睫毛，这四样一去，剩下的轮廓和任意一个卡通小人没有区别。
//   正确的做法不是砍五官，而是【把小人放大到 1.75×】，让像素预算够画眼睛，
//   同时把预算从那些小尺寸下必然糊掉的地方（发丝暗部、扣子高光、裙褶、鞋带）
//   挪走。下面每一层的取舍都按这个原则来。
