// AI 生成内容的**显式标识**该怎么盖 —— 政策只有这一处（铁律六）。
//
// ★★ 为什么单独立一个文件：这是**合规口径**，不是画面效果。它会因为监管解读、平台要求而变，
//   而变的时候不该去动原生编解码代码。合并那条路（utils/nativeMerge → VideoMergePlugin）
//   只认 mode/text/headSec/minSide 四个参数，政策在这里定。
//
// ══ 条文（2026-09-07 逐条查证，链接都是官方原页）══════════════════════════════
//
// ① 《人工智能生成合成内容标识办法》**第四条第一款第（四）项**原文：
//    「在视频起始画面和视频播放周边的适当位置添加显著的提示标识，**可以**在视频末尾和中间
//      适当位置添加显著的提示标识」
//    https://www.cac.gov.cn/2025-03/14/c_1743654684782215.htm
//    ⇒ 「应当」的只有两处：**起始画面** + **播放周边**；末尾与中间是「可以」。
//    ★ 「起始画面**和**播放周边」是**并列**不是二选一，而且「播放周边」是**我们自己的播放器 UI**，
//      它**不跟着文件走** —— 这就是为什么起始画面那一份必须烧进像素（见下面 ③）。
//    ⇒ **视频这一项里没有「每一帧 / 全程」的要求** —— 我们此前那套逐帧角标是自加的，不是条文要求。
//      这就是 2026-09-07 把它改掉的依据。
//    ⚠ 但**别把话说成**"第四条全条没有『持续』字样"（我写错过一次，复核时被抓出来）：
//      第（五）项虚拟场景那条就有 ——「呈现虚拟场景时……**可以**在虚拟场景**持续**服务过程中的适当位置添加」。
//      这反而**加强**结论：立法者知道怎么写「持续标识」，在虚拟场景那一项写了、而且写成「可以」；
//      对视频（第（四）项）连"可以持续"都没写。所以逐帧更没有依据。
//
// ② 强制性国标 **GB 45438-2025** 对视频文字提示的量化要求（网信办官方《一图读懂》第 04 节，
//    https://www.cac.gov.cn/2025-03/15/c_1743755846973028.htm ）：
//      · 位置：起始画面的**边或角**
//      · 字高：**≥ 画面最短边的 5%**
//      · 时长：正常播放速度下**≥ 2 秒**
//      · 文案：须同时含「人工智能」或「AI」**与**「生成」和/或「合成」
//    ⇒ 「只在开头露」不是白拿的：换来的是**短而大**（字要大得多）而不是长而小。
//    ⚠ 国标**正文**我们没读到（openstd 在线预览抓不到全文），以上取自网信办自己的解读长图。
//      要再收紧的话，去核 GB 45438-2025 第 5 章原文。
//
// ③ **第四条第二款**：提供下载/复制/导出功能的，要确保**文件中**含有显式标识。
//    ⇒ 所以不能全改成播放器上叠一层 DOM —— 起始画面那一份必须**烧进像素**。
//
// ④ **第六条**是**传播平台**的义务（在发布内容周边加标识），与第四条（生成方）**并存**，
//    不是二选一。B 站/抖音/快手那种「标题旁标注」落的是第六条；它们只戴这一顶帽子，
//    而我们**两顶都戴**（既生成、又有站内信息流与链接分享）。周边那一半我们已经做了
//    （FeedPage / VideoPage / DiscoverPage 三处，见 components/AigcBadge）。
//
// ⑤ 执法口径（网信办 2025-11-25 集中查处通报
//    https://www.cac.gov.cn/2025-11/25/c_1765795550841819.htm ）点名的是**缺项**：
//    没有显式标识 / 导出文件里没有 / 元数据里没有隐式标识 / 隐式标识位置不规范。
//    **没有任何一条是「显示得不够久」**。所以逐帧→片头是把敞口往下走，不是往上走。
//
// ⚠⚠ 真正还缺的那一格：**隐式标识**（第五条，「应当」）——GB 45438 规定的一段 AIGC 元数据
//   （Label / ContentProducer / ProduceID …）写进文件。我们今天**大概率是零**：成片过去是
//   MediaRecorder 出的 WebM，现在是原生重新编码的 mp4，上游即使写过也在这一步丢光了。
//   数字水印只是「鼓励」不是强制（官方答记者问第二问），顶不了这一格。这件事比角标密度重要，
//   单独列了待办，别因为角标改好了就以为这块也完了。
//
// ⚠ 另一格容易漏：图片那条路（设定帧 / 卡面 / 封面）方舟的 `watermark` **默认是 true**，
//   而 arkClient 传的是 false —— 那是真的把标识摘掉了。视频那条相反（默认就是 false，
//   传不传都一样）。图片若单独对外展示，显式标识要我们自己补。
import type { BadgeMode } from "../utils/nativeMerge";

/** 角标文字。国标要求同时含「AI」与「生成」——这两个字面都在，别改成「AI 制作」之类 */
export const AIGC_BADGE_TEXT = "AI 生成";

/**
 * 盖多久。
 * - `head`（现行）：只在**起始画面**露 `HEAD_SEC` 秒。依据见上面 ①②。
 * - `always`：每一帧都有。超出条文要求，2026-09-07 之前的老做法。
 * - `none`：画面里不盖。**违反第四条第二款**（导出文件里必须有），别用。
 */
const MODE: BadgeMode = "head";

/** 国标下限是 2 秒；给 0.5 秒余量，避免因编码取整擦边 */
const HEAD_SEC = 2.5;

/** 字高占画面**最短边**的比例。国标下限 5%，取 5.5% 留余量 */
const MIN_SIDE_RATIO = 0.055;

/** 交给合并那条路的参数（唯一出口） */
export function aigcBadgeSpec(): { text: string; mode: BadgeMode; headSec: number; minSideRatio: number } {
  return { text: AIGC_BADGE_TEXT, mode: MODE, headSec: HEAD_SEC, minSideRatio: MIN_SIDE_RATIO };
}

/** 现在是不是每帧都盖 —— 给界面上那句说明用，别让文案与实际不一致 */
export function badgeIsPersistent(): boolean {
  return (MODE as BadgeMode) === "always";
}

/**
 * **法务正文**里那半句：画面内标识到底盖成什么样。
 *
 * ★★★ 为什么它必须是个函数而不是抄在 agreements.tsx 里的一句话（2026-09-08 评审抓到）：
 *   那份协议正文里原来写的是「在应用内播放时画面上**持续**显示角标，其中经剪辑页合并导出的
 *   成片会把该角标**逐帧**写入画面本身」—— 两半在实读代码上都已经为假：
 *     ① `drawAigcBadge` 全仓**零调用点**（2026-09-07 撤掉 canvas 录屏时连调用一起删了），
 *        合并走的是原生合成器 + 本文件的 `aigcBadgeSpec()`，`MODE="head"` ⇒ 只烧开头 HEAD_SEC 秒；
 *     ② `AigcBadge` 的渲染点是信息流 / 分区页 / 个人页网格 / 详情页作品信息旁 / 发布页声明条，
 *        **三个播放器里一处都没有** ⇒ "应用内播放时画面上持续显示"这件事根本不存在。
 *   一句法务文本同时说反两件事，而它下一行就写着「不得删除、遮挡或篡改」。⇒ 收口到这里，
 *   盖法一改，协议正文、发布页说明、客服口径同一拍跟着变（铁律六 + 铁律八）。
 * ⚠ 改这里的措辞**不需要**动 `TERMS_UPDATED`（那是"要不要让所有人重新过一次同意门"的另一个决定）。
 */
export function badgeLegalClause(): string {
  if (badgeIsPersistent()) {
    return `成片画面每一帧都带「${AIGC_BADGE_TEXT}」角标，导出到本地的文件里同样有`;
  }
  return (
    `经剪辑页合并导出的成片，会把「${AIGC_BADGE_TEXT}」标识烧进**起始画面约 ${HEAD_SEC} 秒**` +
    `（这一份随文件走，导出到本地也在）；未经合并导出的作品（逐段生成、互动分支）画面内不含该标识`
  );
}

/** 给用户看的一句话：成片里的标识长什么样。★ 与 aigcBadgeSpec 同源，别在页面里另写一遍 */
export function badgeNote(): string {
  if (badgeIsPersistent()) return "成片每一帧右下角都会带「AI 生成」角标。";
  return `成片开头 ${HEAD_SEC} 秒会显示「AI 生成」标识（法规要求，导出的文件里也会有）；作品页与首页另有一处标注。`;
}
