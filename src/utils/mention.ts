// @提及令牌的规则 —— **App 侧唯一一处**（铁律六）。
//
// ★★ 这里的每一条都必须与服务端 `utils/mentionParser.js` 的
//     `/(?<![\w@])@([A-Za-z0-9_-]{1,32})/g` 逐字对应。
//   分叉的代价不是报错，而是**静默失败**：补全面板按 App 这边的规则弹出候选、
//   用户挑了一个人插进正文，服务端却按它自己的规则解析不到 —— 评论发出去了，
//   被 @ 的人永远收不到通知，而正文里那一 @ 看起来一切正常（铁律八）。
//   原来这三条常量在 MentionInput / MentionText 各写了一份（还各写了一遍注释），
//   而这一轮恰好要给它们加**长度上限**：一改就得改两处 —— 那就是必须合并的信号。
//
// ★ 谁在用：
//     · MentionInput  —— 决定"要不要弹补全面板 / 这个候选人能不能插"
//     · MentionText   —— 决定"正文里这一处 @ 该不该点亮成链接"
//   两边问的是同一个问题（服务端会把这一段认成一次提及吗），所以只能有一份答案。

/**
 * 令牌本体的长度上限，与服务端正则里的 `{1,32}` 同一个数。
 *
 * ★★ 为什么必须在 App 侧也挡一道：服务端的正则**只捕获前 32 个字符**，
 *   它不会报错、也不会截断用户的正文 —— 一个 33 字的用户名被 @ 时，服务端拿着
 *   前 32 个字去查库，谁都匹配不上，于是那条提及**凭空消失**。表现是：补全面板里
 *   明明有这个人、也挑中插进去了、评论也发成功了，对方就是收不到。
 *   （反过来把这里放宽也一样错：放宽的那部分只会送用户去撞同一堵墙。）
 * ★ 32 是**跟着服务端走**的既有值（server 仓 utils/mentionParser.js 的
 *   MENTION_TOKEN_RE），不是这边拍的。服务端要改的话，改这一个常量即可。
 */
export const MENTION_NAME_MAX = 32;

/** 令牌里允许出现的单个字符（服务端字符类 `[A-Za-z0-9_-]`）。
 *  用来判"这个令牌到这儿是不是真的结束了"——不判的话 `@alice` 会在 `@alicexyz` 里点亮半截。 */
export const MENTION_NAME_CHAR = /[A-Za-z0-9_-]/;

/**
 * `@` **前面**那个字符：出现这些就说明这个 `@` 根本不是一次提及的开头。
 *
 * 与服务端的前置断言 `(?<![\w@])` 逐字对应（`\w` 无 `u` 标志 = `[A-Za-z0-9_]`）。
 * 那条断言是用来挡**邮箱**的：`bob@alice.com` 里的 `@alice` 服务端从来不算一次提及。
 */
export const MENTION_PREV_BLOCK = /[A-Za-z0-9_@]/;

/** 整串是不是一个服务端认得的令牌本体（不含 `@`）。字符集与长度一起判，缺一不可 */
export function isMentionName(name: string): boolean {
  if (!name || name.length > MENTION_NAME_MAX) return false;
  for (const ch of name) if (!MENTION_NAME_CHAR.test(ch)) return false;
  return true;
}
