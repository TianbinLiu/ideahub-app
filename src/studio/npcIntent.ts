// 对话窗输入行的意图路由。**纯函数、无副作用**——放这儿而不是塞进 store，
// 是为了能给它写判定用例（本仓没有测试框架，用例跑在 design/npc-intent-cases.mjs）。
//
// ★ 两条不变量，是安全属性不是产品取舍：
//   ① **路由的输出空间里不存在"直接花大钱"的分支。** 炼一张卡约 13.7k token，
//      是一次闲聊（约 400）的 34 倍。所以 forge 档只能"打开那个已经会报价的表单"，
//      扣费按钮永远由用户手指按下。
//   ② **能否免确认执行，取决于这一档花不花钱，而不是判得准不准。**
//      于是整套路由的正确性不依赖任何正则的准确率——判错了最多是多点一次按钮。
//
// 口径（写下来免得有人顺手把两边调成一样严）：
//   贵档（炼卡）高精度低召回；便宜档（搜索，本地种子数据 0 成本）放宽召回。
//   漏判炼卡 = 用户多点一次按钮；误判炼卡 = 替他烧 34 次闲聊的钱。
export type NpcIntent = "crisis" | "help" | "forge" | "market" | "chat";

/**
 * 心理危机。**宁可误判，不可漏判**：误判的代价是多出一条服务条，漏判的代价不可接受。
 * 它排在一切之前（早于斜杠命令、早于忙碌闸门之后的任何分支），也**不锁死聊天**
 * ——给完资源用户照常能继续说话。
 */
export const CRISIS_RE =
  /自杀|轻生|自尽|割腕|跳楼|自残|伤害自己|不想活|活不下去|活着(好累|没意思)|结束(我的)?生命|(我|真|好)想死/;

/** 疑问/评价句式 → 降级闲聊。没有这条，「你觉得做卡难吗」会被 FORGE 命中，代价 13.7k */
const ASKING_RE = /[？?]\s*$|吗[。！？!]?\s*$|呢[。！？!]?\s*$|^(你|您)?(觉得|认为|说说|知道|会不会|能不能)/;
const FORGE_VERB_RE = /炼|铸|做(一|张|个|几)|造(一|张|个)|生成|来(一|张|个)|整(一|张|个)|帮我(做|画|炼)/;
const FORGE_NOUN_RE = /卡片?|卡牌|人物卡|角色卡|场景卡|背景卡|道具卡|风格卡/;
const SEARCH_VERB_RE = /找|搜|查|翻|淘|逛|有没有|看看/;
const SEARCH_NOUN_RE = /卡片?|卡牌|素材|市场|别人的|现成/;
/** 帮助排在闲聊之前，两个理由：① 模型不知道界面上有几个按钮，一定会编出不存在的操作
 *  ② 余额为 0 时也应该能得到帮助——这一档是本地文案，0 token、0 延迟 */
const HELP_RE =
  /怎么(用|玩|做|开始|操作|铸|炼)|如何(用|开始)|不(会|知道)(用|怎么)|看不懂|新手|教程|帮助|这(是|个)(什么|啥)|干(嘛|什么)用|(卡片?|卡组|卡位|法阵|市场|工坊|素材)(是|叫)(什么|啥)/;

/** 判定顺序见文件头。斜杠前缀是显式意图，直接短路。 */
export function routeIntent(text: string): NpcIntent {
  const t = text.trim();
  if (CRISIS_RE.test(t)) return "crisis";
  if (/^\/(找|搜)/.test(t)) return "market";
  if (/^\/(炼|卡)/.test(t)) return "forge";
  if (/^\/帮助/.test(t)) return "help";
  if (HELP_RE.test(t)) return "help";
  if (!ASKING_RE.test(t) && FORGE_VERB_RE.test(t) && FORGE_NOUN_RE.test(t)) return "forge";
  // 便宜档不做疑问句排除：放宽召回
  if (SEARCH_VERB_RE.test(t) && SEARCH_NOUN_RE.test(t)) return "market";
  return "chat";
}

/**
 * 从「帮我找找古风的卡」里抽出「古风」。
 *
 * ★ 为什么必须抽：现状是把**整句**丢进 marketSearch，而 mock.searchMarket 是
 *   `name.includes(q)` 的**字面匹配**——整句必然零命中。所以"市场搜什么都搜不到"
 *   的真因在这里，不在搜索本身。
 * 抽不出来时**宁可返回空词**——空词 = 显示最热，比 0 张好。
 *
 * 实测：古风的卡→古风 / 找一张古风卡→古风 / 国风的卡→国风 /
 *      搜赛博朋克素材→赛博朋克 / 看看有没有废土的卡→废土 / 逛市场→""（元词过滤）
 */
export function searchKeyword(text: string): string {
  const q = text
    .trim()
    .replace(/^\/(找|搜)/, "")
    .replace(/^(帮|给|替)我?|^(我想|我要|能不能|可以|麻烦|请)/g, "")
    .replace(
      /(找找|找一?[张个下条]?|搜一?[张个下条]?|搜索|查一?[张个下条]?|翻翻|翻一?[张个下条]?|淘一?[张个下条]?|逛一?逛?|看看有没有|有没有|看看)/g,
      "",
    )
    .replace(/(的|类|风格的)?(卡片?|卡牌|素材|东西)$/g, "")
    .replace(/[的了吗呢吧啊呀？?！!。，,、\s]/g, "")
    .replace(/^(市场|卡片?|素材)$/, "") // 只剩元词 = 没抽到关键词
    .trim();
  return q.length > 0 && q.length <= 12 ? q : "";
}
