/**
 * 合成这一段的要求提示词：骨架 + 作者那句话 → 一段能直接填进输入框的提示词。
 *
 * @throws 合成失败时抛出**整句可显示**的原因。调用方（编辑页）必须把它显示出来，
 *   并让用户**手写**这一段（输入框保持可编辑，也可以拿 `blockoutApplySkeleton`
 *   的骨架当起点）。★ 绝不许 catch 成空串："输入框空着"在界面上和"用户还没写"
 *   长得一模一样，用户会以为自己写了一句就够，出片时那句点名映射整个没发出去 ——
 *   而换错人是零报错的（铁律八）。
 *
 * ★ mock 构建（没配 ARK_API_KEY）直接返回骨架：那**不是**静默降级 —— 骨架本身就是
 *   第五章那份模板，chat 只负责把作者那句话揉得顺一点。返回空串才是降级。
 * ★ 为什么直连 `ai/arkClient.chat` 而不是走 `ai/index` 的出口：`ai/index` 今天唯一的
 *   对话出口是 `npcChat`，而它按 90 字截断回复（NPC 气泡只有三行高）—— 拿它合成
 *   200 字的提示词等于每次都被切掉大半。要收口成统一出口得在 `ai/index` 加一个
 *   文本合成入口，那个文件这一轮不归本施工位改（`utils/mediaUrl.ts` 已有直连先例）。
 */
export async function composeBlockoutPrompt(
  cast: BlockoutCastSlot[],
  userLine: string,
  spec: MarkSpec,
): Promise<string> {
  // ★ 骨架与「这一次给哪几个位子拼了括号」一并取回 —— 下面三道校验都要拿它逐字核对括号内容。
  //   在校验侧重算一遍预算就是同一条规则的第二处实现（详见 buildSkeleton 的 ★★★）。
  const { text: skeleton, usedDesc } = buildSkeleton(cast, userLine, spec);
  // ★★ 下面每一处都用**排好序的**那一份，不是原始 `cast`：给豆包的上下文若按另一个顺序
  //   列，等于在骨架已经排好升序之后又递给它一个反例（而顺序就是语义，见 orderSlots）。
  const slots = orderSlots(cast, spec);
  if (!AI_REAL) return skeleton;
  const line = userLine.trim();
  // 作者一个字都没写 = 没有要"融"的东西，骨架已经是成品。省一次调用，也省一次
  // 「模型把好好的句子改坏」的机会
  if (!line) return skeleton;

  // ★ 预算按**这一次真的挂了几张卡**算（同一张卡挂两个位子只占一份图位，与
  //   flowStore 落 materials 时的去重同口径）——按角色位数量算会白白多留位，
  //   而多留的那部分本来是用户的。
  const cards = new Set(slots.flatMap((s) => (s.card ? [s.card.id] : [])));
  const budget = Math.max(blockoutPromptBudget(cards.size), skeleton.length);
  const context = slots
    .flatMap((s) => (s.card ? [`${labelText(s.label, spec)}（原视频里是${s.desc || "某个人物"}）→ ${s.card.name}`] : []))
    .join("\n");
  let out = "";
  try {
    out = await chat(
      COMPOSE_SYSTEM[spec.scheme],
      [
        "【已写好的提示词】",
        skeleton,
        "",
        "【作者补充的那句话】",
        line,
        "",
        "【角色位对照（仅供你理解，不要写进成品）】",
        context || "（无）",
        "",
        `【长度】全文不超过 ${budget} 个字。`,
      ].join("\n"),
    );
  } catch (e) {
    throw new Error(
      `提示词合成失败（${e instanceof Error ? e.message : String(e)}）——这一段的要求请自己写，或用下面那份默认写法。`,
    );
  }

  const text = out.replace(/```[a-z]*|```/gi, "").trim();
  if (!text) {
    throw new Error("提示词合成失败：AI 什么都没返回——这一段的要求请自己写，或用下面那份默认写法。");
  }
  // ★★ 逐条核对**机器生成的那一半还在不在**。这不是洁癖：模型很爱把「1、2、4、5」
  //   顺手规整成「1、2、3、4」，或者把 `编号1=张三` 改写成读起来更顺的句子 ——
  //   两者都不报错，只表现为出片时换错了人。核不过就整句拒，绝不"差不多就用了"。
  const missLabel = slots.find((s) => !hasLabel(text, s.label, spec));
  if (missLabel) {
    throw new Error(
      `提示词合成失败：AI 改写时把「${labelText(missLabel.label, spec)}」这个角色位弄丢了（${
        spec.scheme === "ordinal" ? "位置换个说法" : "编号错一位"
      }就会把卡换到别人身上）——这一段的要求请自己写，或用下面那份默认写法。`,
    );
  }
  const missPair = slots.find((s) => s.card && !hasPair(text, s.label, s.card.name, spec, usedDesc.get(s.label)));
  if (missPair?.card) {
    throw new Error(
      `提示词合成失败：AI 改写时动了「${labelText(missPair.label, spec)}=${missPair.card.name}」这条绑定（${
        spec.scheme === "ordinal" ? "位置" : "编号"
      }与角色名必须原样成对，配错了就是把卡换到别人身上）——这一段的要求请自己写，或用下面那份默认写法。`,
    );
  }
  // ★★★ 第四道：**顺序**。上面两道都是逐条的，一条都管不到先后 —— 模型完全可以把
  //   `最左边=凛、从左数第3个=张三` 改写成 `从左数第3个=张三、最左边=凛`，两条 hasPair
  //   全过，而那正好就是实测里 5 个位子错 3 个的那一发（序数方案下**书写顺序就是语义**，
  //   见 orderSlots 的 ★★★）。所以顺序必须单独核一次。
  // ★ 挂卡句与空位句**各自内部**升序，不是全体升序：正文里挂卡的先说完、空位的后说，
  //   所以一个排在中间的空位天然出现在所有挂卡位之后。跨组比就会 100% 误报。
  // ★★ **编号方案整条跳过**：编号是印在人偶身上的，模型按号找人，书写顺序不参与语义 ——
  //   给它加一道没有实测依据的顺序闸，只会凭空多一种拒绝（线上那两个模板首当其冲）。
  // ★★ 定位**只认绑定形态**（`最左边=凛` / `最右边的人偶`），不是裸的 `indexOf(label)`：
  //   作者那句话里合法地提到方位很常见（"最左边的灯光很好看"），裸查会命中散文里那一处，
  //   于是一段完全正确的提示词被判成乱序 —— 而校验的假阳性与假阴性一样坏。
  //   ★ 用的正是上面两道已经在用的正则（hasPair / hasLabel 的右边界），不是第二套判据。
  if (spec.scheme === "ordinal") {
    // ★★ 空位那一支的右边界必须与 `hasLabel` **逐字相同**（含 `\s*[=＝]` 那一路），
    //   否则会出现"上一道放行、这一道找不着位置"的**误拒**：模型把空位写成
    //   `最右边=保持白色人偶原样`（骨架里是「最右边的人偶」）时，hasLabel 那条
    //   `[=＝]` 支路认，这里只认「…的人偶」就会 `search` 回 -1，而 -1 在下面的
    //   递增判断里必然判成乱序 —— 一段完全正确的提示词被整段拒掉，用户只能手写。
    //   ⚠ 两处正则的**唯一区别只允许是"要不要带角色名"**；再有第三种差异就说明
    //   这里已经变成第二套判据了，回去合并。
    const posOf = (s: BlockoutCastSlot) => {
      const l = esc(s.label);
      // ★ 与 hasPair 逐字同源：有描述就逐字核对括号内容、名字带右边界（见那两条 ★★★）
      const d = usedDesc.get(s.label);
      const paren = d ? `\\s*[（(]${esc(d)}[）)]` : DESC_PAREN;
      const re = s.card
        ? new RegExp(`${l}${paren}\\s*[=＝]\\s*${esc(s.card.name)}${NAME_END}`)
        : new RegExp(`${l}${paren}(?=\\s*[=＝]|的?人偶)`);
      return text.search(re);
    };
    const ordered = (group: BlockoutCastSlot[]) => {
      let prev = -1;
      for (const s of group) {
        const at = posOf(s);
        if (at <= prev) return false;
        prev = at;
      }
      return true;
    };
    if (!ordered(slots.filter((s) => s.card)) || !ordered(slots.filter((s) => !s.card))) {
      throw new Error(
        "提示词合成失败：AI 改写时把角色位的先后顺序打乱了（这段话必须按画面上从左到右的顺序写，顺序一乱就会换错人——实测同样三张卡，只把顺序写反，5 个位子里就错了 3 个）——这一段的要求请自己写，或用下面那份默认写法。",
      );
    }
  }
  // ★★ 「把编号擦掉」那一句也要核对 —— 它和上面两条是同一类：机器生成、掉了零症状。
  //   模型改写时最爱丢的就是这种"看起来像技术备注"的句子，而丢了的后果是**成片里
  //   人物顶着编号**（2026-08-15 实拍验过，见 blockoutApplySkeleton 的 ★★）——
  //   而那时钱已经花完了，用户只能看着一段废片。
  // ★ 判据放宽到"有没有表达**去掉编号**这个意思"而不是原样比对：这一句允许被揉进
  //   别的句子里（它不像 `编号N=张三` 那样是必须逐字保真的映射）。宁可放过一种
  //   古怪的改写，也不要因为模型换了个动词就把用户整段挡下来。
  // ★★ **序数方案整条跳过**：骨架里本来就没有这句话（人偶身上什么都没印，没有要擦的东西，
  //   见文件头 ★★）。不跳的话，序数模板每一次"作者写了补充要求"的合成都会 100% 抛错，
  //   用户只能手写整段 —— 一条永远为真的失败比没有校验更糟。
  // ★★★ 判据里**必须带上「人偶」**（2026-08-17 修）：原来只查"有没有去掉+编号"，
  //   而被查的这段 `text` 里**混着作者自己那 60 字补充要求**。作者写一句
  //   「画面里不要出现编号或字幕」就能让这道校验恒真 —— 哪怕模型把机器那句整个丢了。
  //   最坏的地方在于它恰好在最需要它的时候失效：上一发被编号毁过的作者，
  //   最可能补的就是这句话。加上「人偶」之后，判的才是机器那半（它说的是"把**人偶**
  //   头上和身上的编号去掉"），作者的泛泛一句不再顶替它。
  // ★ 仍然按**句子**判、且三个要素允许换措辞：这一句允许被揉进别的句子里，
  //   宁可放过一种古怪的改写，也不要因为模型换了个动词就把用户整段挡下来。
  const clearsMarks = text
    // ★★ **中文逗号也是分句符**（2026-08-18 审查抓到）：不切它的话，作者一句
    //   「人偶动作要连贯，不要出现编号」就把「人偶」「不要」「编号」三个词凑进同一"句"，
    //   连上一轮刚加的「人偶」那道一起顶替掉 —— 而它恰好在最需要它的时候失效
    //   （上一发被编号毁过的作者，最可能补的就是这句话）。
    //   ★ 机器那句本身含中文逗号（「…全部去掉，成片里不许出现任何编号或数字。」），
    //     但切开后前半句仍然同时含有 去掉/编号/人偶，照样放行 —— 验算过。
    .split(/[。；;!！，,\n]/)
    .some(
      (s) =>
        // ★ 动词放得比原来更松（不再要求"不许**出现**"这种固定搭配）：真正把假阳性
        //   挡住的是下面那两个**同句共现**的名词，动词严一点只会误伤合理的改写
        /(去掉|去除|抹掉|擦掉|删掉|不保留|不许|不要|不得|不能|没有)/.test(s) &&
        /(编号|数字|号码)/.test(s) &&
        /人偶/.test(s),
    );
  if (spec.scheme === "number" && !clearsMarks) {
    throw new Error(
      "提示词合成失败：AI 改写时把「去掉人偶身上的编号」这句丢了（丢了的话成片里人物头上会顶着编号，钱花完才看得出来）——这一段的要求请自己写，或用下面那份默认写法。",
    );
  }
  return text;
}
