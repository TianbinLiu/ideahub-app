// 白模模板「套用」那一段提示词的合成 —— **全仓唯一实现**（方案 WM_V2 第五章）。
//
// 这条链路上有两段提示词，这里只放**第二段**：
//   ① 白模化（把作者自己的视频里的人全换成带标记的白模人偶）—— 由**服务端**拼，
//      不在本仓（它要跟着「先看」那一步的视觉结果逐个点名，客户端根本没有那份清单）；
//   ② 套用（别人给每个人偶挂上人物卡，出片时把白模换回真人）—— 就是本文件。
//
// ★★★ 2026-08-17：标记换成「人偶**全都是一模一样的纯白色**、身上什么都不印，套用时用
//   **序数措辞**（「最左边」「从左数第3个」「最右边」）指认」。**两套措辞都要留着**，按模板
//   分方案 —— 线上已经存在的 6 个模板（人偶身上印的是数字）里有两个是好的、还在被人用的
//   （「都市主角群舞转场」「宗主垫脚舞」）。套用提示词一刀切改成「最左边=凛」，它们
//   **当场作废**（模型在一群印着号的人偶里没有"最左边"这个锚点该有的语义），而且零报错。
//   所以本文件里每一处涉及标记的地方都收一个 `spec: MarkSpec` 参数，判据由调用方从模板
//   带下来（唯一实现是 data/templates.markSpecOf，**缺省 = 编号**）。
//   ⚠ 编号版那一份是**存量行为的逐字副本**，改它之前先想清楚线上那两个模板会怎样。
//   ⚠ 中间还有过一代「一位一色」，2026-08-17 整档删掉（线上颜色模板 0 个、在途凭据 0 条，
//     它从没产出过任何东西）—— 复盘见 data/templates 的 isOrdinalMark 上面那段。
//
// ★★ 为什么序数版**不需要**「把标记去掉」那一句（这是两套措辞最大的结构差异）：
//   编号必须擦，是因为号是**我们印上去的记号**、会被 r2v 逐帧原样搬进成片（实拍：换上去的
//   角色后脑顶着「1」）。而序数方案下人偶身上**什么都没有** —— 没有要擦的东西，这是
//   **结构上不存在**，比颜色那一代"实测不渗透所以不加"的理由更硬。
//   ⚠ 顺带还掉一笔颜色时代的债：没挂卡的位子在成片里会是**一个纯白人偶**（看起来像风格化），
//   而不是颜色时代那个"紫色塑料人"（观众只会觉得是 bug）。所以挂卡面板上那句"没挂的会
//   怎样"这一版可以说实话、也不用再劝用户挂满。
//
// ★★★ **升序是承重的，不是读起来顺。** 实测（2026-08-17，付费实拍）：同样 3 张卡、同样
//   3 个目标位置、同样 2 个空位，只把指令的**书写顺序**从 (第2→最右→第3) 改成
//   (第2→第3→最右)，结果从 **2/5 变成 5/5**，乱序那一发还多出一个重复角色。
//   机理：这个模型是在**对齐两个序列**（指令序列 ↔ 画面从左到右的序列），不是在解析符号 ——
//   升序时"顺着往下贴"与"按序数找"给出同一答案，乱序就露馅。
//   ⇒ 拼这段话之前**必须**按位置升序排一次（`orderSlots`，本文件唯一实现）。用户界面上
//   怎么点都行，内部排一次。谁觉得"按点击顺序更自然"改回去，症状是**换错人 + 多出重复
//   角色**，全程零报错，要花一次钱才看得见。
//
// ★★ 为什么合成的结果要**填进用户的要求输入框**而不是在出片时偷偷拼上去：
//   这段话决定"哪个人偶换成谁"，换错人是**画面照出、零报错**的故障，只有作者肉眼能发现。
//   摆在输入框里，用户出片前一定会看见它、也随时能改；藏在代码里，他连"模型被告知了什么"
//   都不知道。改完**以输入框为准**（segmentGen 那边对有 roles 的模板不再拼 BLOCKOUT_SWAP，
//   就是为了不和这段话打架）。
//
// ★★ 2026-08-15：整段改成**紧凑措辞**（`编号1=张三`），措辞省下的字全部留给用户。
//   原因是角色位上限从"实际能挂 3 个"放到了 9 个（参考图预算跟随方舟协议 30 张，见
//   ai/real 的 ARK_REF_IMAGES_MAX），而提示词硬顶 `VIDEO_PROMPT_MAX` 一个字没涨：
//   老措辞（「编号 N 的白色人偶替换为角色「XX」」每位 19 字 + 结尾那段 68 字的动作清单）
//   在 9 个角色位下光骨架就 300 字，加上出片时挂在尾巴上的绑定句直接溢出 ——
//   而溢出是**从正文这头切**的（segmentGen 的 room），切掉的正是用户自己写的那几句。
//   紧凑不等于天书：`编号1=张三` 一眼能懂、能手改，这是硬要求（这段话是给用户读的）。
