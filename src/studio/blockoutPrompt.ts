// 白模模板「套用」那一段提示词的合成 —— **全仓唯一实现**（方案 WM_V2 第五章）。
//
// 这条链路上有两段提示词，这里只放**第二段**：
//   ① 白模化（把作者自己的视频里的人全换成带编号的白模人偶）—— 由**服务端**拼，
//      不在本仓（它要跟着「先看」那一步的视觉结果逐个点名，客户端根本没有那份清单）；
//   ② 套用（别人给每个编号的人偶挂上人物卡，出片时把白模换回真人）—— 就是本文件。
//
// ★★ 为什么合成的结果要**填进用户的要求输入框**而不是在出片时偷偷拼上去：
//   这段话决定"哪个编号换成谁"，换错人是**画面照出、零报错**的故障，只有作者肉眼能发现。
//   摆在输入框里，用户出片前一定会看见它、也随时能改；藏在代码里，他连"模型被告知了什么"
//   都不知道。改完**以输入框为准**（segmentGen 那边对有 roles 的模板不再拼 BLOCKOUT_SWAP，
//   就是为了不和这段话打架）。
//
// ★★ 2026-08-15：整段改成**紧凑措辞**（`编号1=张三`），措辞省下的字全部留给用户。
//   原因是角色位上限从"实际能挂 3 个"放到了 9 个（参考图预算跟随方舟协议 30 张，见
//   ai/real 的 ARK_REF_IMAGES_MAX），而提示词硬顶 `VIDEO_PROMPT_MAX` 一个字没涨：
//   老措辞（「编号 N 的白色人偶替换为角色「XX」」每位 19 字 + 结尾那段 68 字的动作清单）
//   在 9 个角色位下光骨架就 300 字，加上出片时挂在尾巴上的绑定句直接溢出 ——
//   而溢出是**从正文这头切**的（segmentGen 的 room），切掉的正是用户自己写的那几句。
//   紧凑不等于天书：`编号1=张三` 一眼能懂、能手改，这是硬要求（这段话是给用户读的）。
import { AI_REAL, VIDEO_PROMPT_MAX } from "../ai";
import { chat } from "../ai/arkClient";
import type { Card } from "../types";

/** 一个角色位 + 它挂上了谁。编辑页把 `template.roles` 与用户挂的卡合成这张表交过来 */
export interface BlockoutCastSlot {
  /**
   * 人偶身上那个编号 —— **原样来自 `template.roles[].label`**。
   *
   * ★★ 实测**稳定但不连续**（2026-08-15 一发四个人偶实出 1/2/4/5）。所以：
   *   别按下标推编号、别拿 `roles.length` 当最大编号、这里**原样用**，
   *   不许"顺手规整成 1..N" —— 对着 4 号说 3 号的话，模型就把卡换到别人身上。
   * ★ 编号印在**头部前后左右四面**（同一个数字），不再只印胸口（2026-08-15 起，服务端
   *   白模化提示词那侧同一次改动）：胸口那个一转身/一背对镜头就没了，而编号是
   *   「点这个人偶挂这张卡」的唯一连接键 —— 看不见编号，用户连挂卡都开始不了。
   */
  label: string;
  /** 这个位子在原视频里替换掉的是谁（`roles[].desc`，如「穿黑袍的白发少年」）。
   *  只进 chat 的上下文，**不进成品提示词** —— 成品里说的是"换成谁"，不是"原来是谁"。 */
  desc: string;
  /** 挂上的人物卡；null = 没挂（这个人偶保持白模原样） */
  card: Card | null;
}

/**
 * 出片时挂在提示词**尾巴**上的绑定句要占多少字 —— 合成这一步的**预留位**。
 *
 * ★ 不是拍脑袋：按 `ai/real.prepareMaterialRefs` 的紧凑式绑定量出来的 ——
 *   每张卡一条 `张三=@图片1@图片2`（名字 ≈3 + 等号 1 + 两个 `@图片N` 各 4 + 分隔 1 ≈ 13 字），
 *   外加头尾那句「参考图：…只用来锁这个角色的长相、发色与服装，不要照抄其构图与背景。」≈ 40 字。
 * ★ 宁可**估大**：估小了 segmentGen 会从正文尾巴切一刀，切掉的是「不要出现字幕」这类
 *   收尾要求，或者用户自己补的那句话 —— 而那一刀虽然会当场报出来，用户也只能回来重写。
 * ⚠ 这是**镜像**，不是那条规则本身：绑定句的真正形态在 `ai/real` 的 `bind()`。
 *   改那边的措辞就要回来重量一次（两边一起漂时没有任何症状，只表现为正文被多切几个字）。
 */
const BIND_RESERVE_FIXED = 40;
const BIND_RESERVE_PER_CARD = 13;

/**
 * 合成结果的字数上限：把尾巴的位置先留出来，剩下的**全给用户**。
 *
 * ★ 这不是方舟的限制，是**预算**：硬顶是 `ai.VIDEO_PROMPT_MAX`（400 字），
 *   而截断是从正文这头切的。挂 9 张卡时尾巴约 40+9×13 = 157 字，这里就只准写到 243 字。
 * ★ 下限 80：卡再多也得给正文留一口气 —— 真到那一步，溢出会被 segmentGen 整句报出来
 *   （那才是唯一可靠的一环），而不是悄悄少发几句。
 */
export function blockoutPromptBudget(cardCount: number): number {
  return Math.max(80, VIDEO_PROMPT_MAX - BIND_RESERVE_FIXED - Math.max(0, cardCount) * BIND_RESERVE_PER_CARD);
}

/** 角色位排序：**只为读起来顺**，按编号的数值升序（认不出数字的排最后、保持原序）。
 *  ★ 排序不改 label 本身 —— 编号不连续是实测事实，这里只是让「1、2、4、5」按人眼习惯排。 */
function byLabel(a: BlockoutCastSlot, b: BlockoutCastSlot): number {
  const na = Number.parseInt(a.label, 10);
  const nb = Number.parseInt(b.label, 10);
  if (Number.isNaN(na) && Number.isNaN(nb)) return 0;
  if (Number.isNaN(na)) return 1;
  if (Number.isNaN(nb)) return -1;
  return na - nb;
}

/**
 * 「这个名字能不能直接写进紧凑绑定里」—— null = 能，否则是一句给用户看的整句原因。
 *
 * ★★ 紧凑式（`编号1=张三`、出片时 `张三=@图片1@图片2`）拿 `=`、`；`、`、` 当分隔符，
 *   而角色名是**用户/豆包写的**。名字里混进这几个字符，模型就会把一条绑定读成两条
 *   （或把半个名字当成图片编号）—— 表现是换错人/漏换人，**画面照出、钱照收、零报错**。
 *   老措辞用「」把名字括起来，天然没有这个问题；这是紧凑化换来的新风险，所以必须
 *   在花钱之前**响亮地**拦一次（铁律八），而不是在提示词里悄悄替换掉那几个字符 ——
 *   替换会让这一头的名字与出片时绑定句里的名字对不上，那正是同一个故障的另一种形状。
 * ★ 唯一实现：挂卡那一处（flowStore.applyCast）调它，别在别处再判一遍。
 */
export function castNameIssue(name: string): string | null {
  const bad = ["=", "＝", "；", ";", "、", "@", "＠", "\n"].filter((ch) => name.includes(ch));
  if (bad.length === 0) return null;
  return `角色名「${name}」里有 ${bad.map((c) => `「${c === "\n" ? "换行" : c}」`).join("")}——出片时"哪个编号换成谁"是用这几个符号分隔的，名字里带着它们会让 AI 把一条绑定读成两条（换错人不会报错，只有你自己看得出来）。请给这张卡改个名字`;
}

/**
 * 骨架（方案第五章「套用」那段模板的**紧凑版实现**）—— 纯函数，不打网络。
 *
 * ★★ 它是**确定性**的，这一点不能让给模型：`编号N=角色名` 的对应关系是机器生成、
 *   用户改得动但模型改不得的那一半，任何"顺手重编号/顺手改个名"都会让卡换到别人身上
 *   （F5）。所以 chat 那一步只许**把作者那句话揉进去**，揉完还要逐条核对这些串还在
 *   （见 composeBlockoutPrompt 的校验）。
 *
 * ★ 与方案第五章的**一处有意偏离**：模板里写的是「编号 N 的白色人偶替换为 <图片M> 的角色」，
 *   这里写的是 `编号N=角色名`。原因：`<图片M>` 的编号**在这一刻还不存在** ——
 *   它由出片时的 `prepareMaterialRefs` 现分配（谁被挤掉、同一张卡的图还要连号），
 *   而那一步产出的绑定句已经把 `@图片M` 与角色名绑好了。在这里猜一个 M 写死，正是 F5
 *   警告的那种"编号对不上就换错人"，只是搬到了上一层。走名字，两段话自然接得上：
 *   这里说「编号4=张三」，绑定句说「张三=@图片2」。
 *   ★ 还有一条**同样要紧**的理由：名字这一跳让**用户的改动始终说了算**。他在输入框里
 *   把「编号1=张三」改成「编号1=李四」，尾巴上的 `张三=@图片1`／`李四=@图片3` 两条都还在，
 *   模型照他改的走；这里若写死图片编号，用户一改就与尾巴当场打架，而模型只会挑一句听。
 *
 * ★ 没挂卡的位子**每一个都带上「编号」两个字**（`编号4、编号5` 而不是 `编号4、5`）：
 *   合成后的校验按「编号N」逐个找回来（hasLabel），写成顿号列表的话第二个之后一律找不到，
 *   于是**每次都误判成"AI 把这个角色位弄丢了"**并整句拒绝合成 —— 2026-08-15 改造前
 *   就是这个形状（两个以上空位 + 用户写了补充要求 = 必定合成失败）。多两个字买一个
 *   不会误报的校验，划算。
 */
export function blockoutApplySkeleton(cast: BlockoutCastSlot[], userLine = ""): string {
  const slots = [...cast].sort(byLabel);
  // flatMap 而不是 filter：filter 之后 TS 仍然认为 card 可能是 null，只能靠 `!` 硬压 ——
  // 而这一句正是"哪个编号换成谁"的正文，压错了没有任何报错，只是换错人
  const taken = slots.flatMap((s) => (s.card ? [{ label: s.label, name: s.card.name }] : []));
  const free = slots.filter((s) => !s.card);
  const parts: string[] = ["以参考视频复刻原视频的人物站位、动作、节奏卡点、运动轨迹、队形与运镜。"];
  if (taken.length > 0) {
    parts.push(`把带编号的白色人偶替换为对应角色：${taken.map((s) => `编号${s.label}=${s.name}`).join("、")}。`);
  }
  if (free.length > 0) {
    // ★ 没挂卡的**也要点名说"保持原样"**，不能只靠"没提到就是不动"：模型对没提到的
    //   主体会自己发挥（实测白模化那一发正是"泛指会漏掉主角"的同一个机理，F4）。
    parts.push(`${free.map((s) => `编号${s.label}`).join("、")}保持白色人偶原样不变。`);
  }
  // ★ 这一句 2026-08-15 从 68 字压到 25 字（原文逐项列了抬手/摆臂/身体倾斜/弹跳/重心变化…）。
  //   压得起的依据：r2v `edit` 子任务**本身**就是逐帧复刻（它的立身之本是"保住主体、复刻其余"，
  //   F4 实测），这句话是加一道保险、不是唯一依靠。省下的 43 字全部进了用户的额度。
  //   ⚠ 万一以后发现复刻精度掉了，**第一个该恢复的就是它**（先恢复这句，再考虑砍别的）。
  parts.push("动作、起止时间、落点与强拍定格都要与参考视频一致。");
  const line = userLine.trim();
  if (line) parts.push(line.endsWith("。") ? line : `${line}。`);
  parts.push("不要出现字幕。");
  return parts.join("");
}

/**
 * 「合成结果里还有没有这个编号」。
 *
 * ★ 必须卡住**右边界**：`text.includes("编号 1")` 会被句子里的「编号 12」命中 ——
 *   于是"1 号被 AI 弄丢了"这件事被 12 号顶掉，检查形同虚设。而检查一旦有假阳性，
 *   就等于我们**以为**核对过了（比不核对更坏）。
 * ★ 左边界不卡：中间那个空格模型很爱吞掉（「编号1」），那是排版不是语义。
 */
function hasLabel(text: string, label: string): boolean {
  return new RegExp(`编号\\s*${esc(label)}(?![0-9])`).test(text);
}

/**
 * 「`编号N=角色名` 这条绑定还原样在不在」—— 比 hasLabel 更严的一档。
 *
 * ★★ 光查"编号还在""名字还在"是不够的：模型很爱把 `编号1=张三、编号2=李四` 改写成
 *   「让张三站在编号 2 的位置上」这种读起来更顺的句子 —— 编号在、名字也在，**配对却反了**，
 *   而配错的表现是换错人（画面照出、零报错）。所以这里核的是**整条配对**。
 * ★ 只放过排版级的差异（编号前后的空格、等号两边的空格、全角等号）；语序一变就算失败，
 *   整句拒 + 让用户自己写（宁可多拒一次，也不能把一条错的映射当成对的发出去）。
 */
function hasPair(text: string, label: string, name: string): boolean {
  return new RegExp(`编号\\s*${esc(label)}(?![0-9])\\s*[=＝]\\s*${esc(name)}`).test(text);
}

/** 正则转义：角色名是用户/豆包写的，里面的 `(`、`+` 之类会把正则整个改写掉 */
function esc(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

const COMPOSE_SYSTEM = [
  "你是视频生成提示词的编辑。用户会给你一段已经写好的中文提示词，以及作者补充的一句话。",
  "你唯一的任务：把作者那句话自然地融进这段提示词，让全文读起来像一段连贯的中文。",
  "硬性要求（违反任何一条都算失败）：",
  "1. 「编号N=角色名」这种等号绑定必须**逐字原样**保留：编号、等号、角色名一个字都不能改，",
  "   不许调换等号两边，不许改写成句子，不许重新编号（编号不连续是正常的）；",
  "2. 不许改动或删除任何一个「编号N」，包括那些说「保持白色人偶原样」的；",
  "3. 不许增加原文没有的画面要求，也不许删掉原文任何一条要求；",
  "4. 直接输出成品正文，不要解释、不要加引号、不要用 Markdown、不要分点。",
].join("\n");

/**
 * 合成这一段的要求提示词：骨架 + 作者那句话 → 一段能直接填进输入框的提示词。
 *
 * @throws 合成失败时抛出**整句可显示**的原因。调用方（编辑页）必须把它显示出来，
 *   并让用户**手写**这一段（输入框保持可编辑，也可以拿 `blockoutApplySkeleton`
 *   的骨架当起点）。★ 绝不许 catch 成空串："输入框空着"在界面上和"用户还没写"
 *   长得一模一样，用户会以为自己写了一句就够，出片时那句点名映射整个没发出去 ——
 *   而换错人是零报错的（铁律八）。
 *
 * ★ mock 构建（没配 ARK_API_KEY）直接返回骨架：那**不是**静默降级 —— 骨架本身就是
 *   第五章那份模板，chat 只负责把作者那句话揉得顺一点。返回空串才是降级。
 * ★ 为什么直连 `ai/arkClient.chat` 而不是走 `ai/index` 的出口：`ai/index` 今天唯一的
 *   对话出口是 `npcChat`，而它按 90 字截断回复（NPC 气泡只有三行高）—— 拿它合成
 *   200 字的提示词等于每次都被切掉大半。要收口成统一出口得在 `ai/index` 加一个
 *   文本合成入口，那个文件这一轮不归本施工位改（`utils/mediaUrl.ts` 已有直连先例）。
 */
export async function composeBlockoutPrompt(cast: BlockoutCastSlot[], userLine = ""): Promise<string> {
  const skeleton = blockoutApplySkeleton(cast, userLine);
  if (!AI_REAL) return skeleton;
  const line = userLine.trim();
  // 作者一个字都没写 = 没有要"融"的东西，骨架已经是成品。省一次调用，也省一次
  // 「模型把好好的句子改坏」的机会
  if (!line) return skeleton;

  // ★ 预算按**这一次真的挂了几张卡**算（同一张卡挂两个位子只占一份图位，与
  //   flowStore 落 materials 时的去重同口径）——按角色位数量算会白白多留位，
  //   而多留的那部分本来是用户的。
  const cards = new Set(cast.flatMap((s) => (s.card ? [s.card.id] : [])));
  const budget = Math.max(blockoutPromptBudget(cards.size), skeleton.length);
  const context = cast
    .flatMap((s) => (s.card ? [`编号${s.label}（原视频里是${s.desc || "某个人物"}）→ ${s.card.name}`] : []))
    .join("\n");
  let out = "";
  try {
    out = await chat(
      COMPOSE_SYSTEM,
      [
        "【已写好的提示词】",
        skeleton,
        "",
        "【作者补充的那句话】",
        line,
        "",
        "【角色位对照（仅供你理解，不要写进成品）】",
        context || "（无）",
        "",
        `【长度】全文不超过 ${budget} 个字。`,
      ].join("\n"),
    );
  } catch (e) {
    throw new Error(
      `提示词合成失败（${e instanceof Error ? e.message : String(e)}）——这一段的要求请自己写，或用下面那份默认写法。`,
    );
  }

  const text = out.replace(/```[a-z]*|```/gi, "").trim();
  if (!text) {
    throw new Error("提示词合成失败：AI 什么都没返回——这一段的要求请自己写，或用下面那份默认写法。");
  }
  // ★★ 逐条核对**机器生成的那一半还在不在**。这不是洁癖：模型很爱把「1、2、4、5」
  //   顺手规整成「1、2、3、4」，或者把 `编号1=张三` 改写成读起来更顺的句子 ——
  //   两者都不报错，只表现为出片时换错了人。核不过就整句拒，绝不"差不多就用了"。
  const missLabel = cast.find((s) => !hasLabel(text, s.label));
  if (missLabel) {
    throw new Error(
      `提示词合成失败：AI 改写时把「编号${missLabel.label}」这个角色位弄丢了（编号错一位就会把卡换到别人身上）——这一段的要求请自己写，或用下面那份默认写法。`,
    );
  }
  const missPair = cast.find((s) => s.card && !hasPair(text, s.label, s.card.name));
  if (missPair?.card) {
    throw new Error(
      `提示词合成失败：AI 改写时动了「编号${missPair.label}=${missPair.card.name}」这条绑定（编号与角色名必须原样成对，配错了就是把卡换到别人身上）——这一段的要求请自己写，或用下面那份默认写法。`,
    );
  }
  return text;
}
